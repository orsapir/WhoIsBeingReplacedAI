#!/usr/bin/env python3
"""Build assets/jobs.js from the curated job list and the two source datasets.

Inputs
  data/jobs_he.psv                              curated jobs (SOC code, Hebrew name, emoji)
  data/sources/frey_osborne_2013.csv            Frey & Osborne (2013) appendix, 702 occupations
  data/sources/microsoft_ai_applicability_2025.csv
                                                Tomlinson et al. (2025), AI applicability per SOC code

Run from the repository root:
  python3 scripts/build_data.py           # writes assets/jobs.js
  python3 scripts/build_data.py --check   # also prints every job next to its source titles
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CURATED = ROOT / "data" / "jobs_he.psv"
FREY_OSBORNE = ROOT / "data" / "sources" / "frey_osborne_2013.csv"
MICROSOFT = ROOT / "data" / "sources" / "microsoft_ai_applicability_2025.csv"
OUT = ROOT / "assets" / "jobs.js"


def load_frey_osborne():
    rows = {}
    with open(FREY_OSBORNE, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows[r["_ - code"]] = {
                "rank": int(r["_ - rank"]),
                "p": float(r["prob"]),
                "title": r["occupation"].strip(),
            }
    if len(rows) != 702:
        sys.exit(f"expected 702 Frey & Osborne occupations, found {len(rows)}")
    return rows


def load_microsoft():
    with open(MICROSOFT, encoding="utf-8") as f:
        return {
            r["SOC Code"]: {"score": float(r["ai_applicability_score"]), "title": r["title"].strip()}
            for r in csv.DictReader(f)
        }


def load_curated():
    jobs = []
    with open(CURATED, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("|")
            if len(parts) != 4:
                sys.exit(f"{CURATED.name}:{n}: expected 4 fields, got {len(parts)}")
            jobs.append(dict(zip(("soc", "ms_soc", "emoji", "he"), (p.strip() for p in parts)), line=n))
    return jobs


def main():
    fo = load_frey_osborne()
    ms = load_microsoft()
    curated = load_curated()

    seen = set()
    out = []
    checks = []
    for job in curated:
        soc = job["soc"]
        where = f"{CURATED.name}:{job['line']}"
        if soc in seen:
            sys.exit(f"{where}: duplicate SOC code {soc}")
        seen.add(soc)
        if soc not in fo:
            sys.exit(f"{where}: {soc} is not in the Frey & Osborne table")

        ms_soc = job["ms_soc"] or soc
        if ms_soc == "-":
            ms_row = None
        elif ms_soc in ms:
            ms_row = ms[ms_soc]
        else:
            sys.exit(f"{where}: {ms_soc} is not in the Microsoft table (use '-' if there is no match)")

        out.append({
            "soc": soc,
            "he": job["he"],
            "emoji": job["emoji"],
            "en": fo[soc]["title"],
            "p": fo[soc]["p"],
            "ms": round(ms_row["score"], 2) if ms_row else None,
        })
        checks.append((fo[soc]["p"], soc, fo[soc]["title"], ms_soc if ms_row else None, ms_row, job["he"]))

    if "--check" in sys.argv:
        for p, soc, en, ms_code, ms_row, he in sorted(checks):
            ms_part = f"{ms_row['score']:.2f} {ms_code} {ms_row['title']}" if ms_row else "—"
            print(f"{p:<7} {soc} {en[:55]:<55} | {ms_part[:50]:<50} | {he}")

    body = ",\n".join("  " + json.dumps(j, ensure_ascii=False) for j in out)
    # newline="\n" keeps LF endings on Windows too, so the CI sync check stays stable.
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "// Generated by scripts/build_data.py from data/jobs_he.psv and data/sources/. Do not edit by hand.\n"
            f"window.JOBS = [\n{body}\n];\n"
        )
    with_ms = sum(1 for j in out if j["ms"] is not None)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} jobs, {with_ms} with a Microsoft score", file=sys.stderr)


if __name__ == "__main__":
    main()
